export function sourceLinks(ids) {
  return ids.filter(id => sources[id].url).map(id => {
    const source = sources[id];
    return `<a href="${source.url}" target="_blank" rel="noopener noreferrer">${source.label}</a>`;
  }).join(' · ');
}

export function sourceReviewLabel(ids) {
  const dates = [...new Set(ids.map(id => sources[id].reviewedOn || reviewedOn))].sort();
  return dates.map(date => new Intl.DateTimeFormat('es', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(new Date(date + 'T00:00:00Z'))).join('; ');
}
